#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# gen_version.py: 构建前读取 Git 信息, 生成 version_generated.h 供固件编译引用。
# 设计要点:
#  1) 仅当生成内容与现有文件不同才写回, 避免每次构建触发全量重编译;
#  2) 无 .git / git 命令失败 / 浅克隆等场景一律兜底为 unknown, 退出码始终为 0, 不阻断构建;
#  3) 所有输出字符串做 ASCII 清洗, 满足 HMI 显示文本 7 位 ASCII 铁律。

import os
import subprocess
import sys
from datetime import datetime


def find_repo_root(start):
    # 从脚本目录逐级向上, 找到含 .git(目录或 worktree 文件)的仓库根
    cur = os.path.abspath(start)
    while True:
        if os.path.exists(os.path.join(cur, ".git")):
            return cur
        parent = os.path.dirname(cur)
        if parent == cur:
            return None
        cur = parent


def run_git(root, args):
    try:
        result = subprocess.run(
            ["git"] + args,
            cwd=root,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=10,
        )
        if result.returncode == 0:
            return result.stdout.decode("utf-8", errors="replace").strip()
    except Exception:
        pass
    return None


def ascii_clean(value, fallback="unknown"):
    # 非 ASCII 字节替换为下划线, 保证下发到屏幕的字符串只含 7 位 ASCII
    if not value:
        return fallback
    return value.encode("ascii", errors="replace").decode("ascii").replace("?", "_")


def collect(root):
    info = {
        "hash": "00000000",
        "branch": "unknown",
        "build_no": 0,
        "dirty": 1,
        "describe": "unknown",
        "build_time": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
    }
    if not root:
        return info

    commit = run_git(root, ["rev-parse", "--short=8", "HEAD"])
    if commit:
        info["hash"] = ascii_clean(commit)

    branch = run_git(root, ["rev-parse", "--abbrev-ref", "HEAD"])
    if branch:
        info["branch"] = "detached" if branch == "HEAD" else ascii_clean(branch)

    count = run_git(root, ["rev-list", "--count", "HEAD"])
    if count and count.isdigit():
        info["build_no"] = int(count)

    porcelain = run_git(root, ["status", "--porcelain"])
    # 干净工作区输出空串; 命令失败返回 None 时保守判为 dirty
    info["dirty"] = 0 if porcelain == "" else 1

    describe = run_git(root, ["describe", "--tags", "--always", "--dirty", "--abbrev=8"])
    if describe:
        info["describe"] = ascii_clean(describe)
    else:
        suffix = "-dirty" if info["dirty"] else ""
        info["describe"] = "g" + info["hash"] + suffix

    return info


def render(info):
    git_short = "{0}-g{1}".format(info["build_no"], info["hash"])
    if info["dirty"]:
        git_short += "-dirty"
    lines = [
        "// Auto-generated by gen_version.py. DO NOT EDIT. This file is git-ignored.",
        "#ifndef __VERSION_GENERATED_H__",
        "#define __VERSION_GENERATED_H__",
        "",
        '#define FW_GIT_HASH       "{0}"'.format(info["hash"]),
        '#define FW_GIT_BRANCH     "{0}"'.format(info["branch"]),
        "#define FW_GIT_BUILD_NO   {0}".format(info["build_no"]),
        "#define FW_GIT_DIRTY      {0}".format(info["dirty"]),
        '#define FW_GIT_DESCRIBE   "{0}"'.format(info["describe"]),
        '#define FW_VERSION_GIT    "{0}"'.format(git_short),
        '#define FW_BUILD_TIME     "{0}"'.format(info["build_time"]),
        "",
        "#endif",
        "",
    ]
    return "\r\n".join(lines)


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    root = find_repo_root(script_dir)
    info = collect(root)
    content = render(info)
    out_path = os.path.join(script_dir, "version_generated.h")

    # utf-8-sig 写入带 BOM, 符合工程新文件 UTF-8 BOM 约定; 行尾已统一为 CRLF
    encoded = content.encode("utf-8-sig")
    old = None
    if os.path.exists(out_path):
        with open(out_path, "rb") as handle:
            old = handle.read()
    if old != encoded:
        with open(out_path, "wb") as handle:
            handle.write(encoded)
        print("gen_version: updated -> " + out_path)
    else:
        print("gen_version: unchanged -> " + out_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
